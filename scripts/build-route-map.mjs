// Generates the static outline used by the home route map (no map library or tiles at runtime).
// Source: Natural Earth 1:50m via world-atlas (public domain data, ISC package).
// Run: npm run map   (output is committed)
import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { filter, filterWeight, presimplify, quantile, simplify } from 'topojson-simplify'

const require = createRequire(import.meta.url)
// Keep ~30% of the points and drop tiny islands: plenty for a ~400px drawing.
const raw = presimplify(require('world-atlas/countries-50m.json'))
const world = filter(simplify(raw, quantile(raw, 0.3)), filterWeight(raw, 0.00002))

const WIDTH = 400
const HEIGHT = 520
const PADDING = 12
// Southern South America, from São Paulo down to Tierra del Fuego.
const WEST = -77
const EAST = -43
const NORTH = -21
const SOUTH = -56

const bbox = {
  type: 'Polygon',
  // Clockwise ring (d3-geo treats counter-clockwise rings as "everything except this box").
  coordinates: [[[WEST, NORTH], [EAST, NORTH], [EAST, SOUTH], [WEST, SOUTH], [WEST, NORTH]]],
}

const projection = geoMercator()
  .fitExtent([[PADDING, PADDING], [WIDTH - PADDING, HEIGHT - PADDING]], bbox)
  .clipExtent([[0, 0], [WIDTH, HEIGHT]])
const path = geoPath(projection).digits(1)

const land = feature(world, world.objects.land)
const countries = feature(world, world.objects.countries)
const argentina = countries.features.find((country) => country.properties.name === 'Argentina')
if (!argentina) throw new Error('Argentina not found in world-atlas')

/** Drops sub-paths (islets, lakes, slivers) smaller than `minSize` px in both directions. */
function dropTinyShapes(d, minSize = 2) {
  return d
    .split('M')
    .filter(Boolean)
    .filter((sub) => {
      const nums = sub.match(/-?\d+(\.\d+)?/g)?.map(Number) ?? []
      const xs = nums.filter((_, i) => i % 2 === 0)
      const ys = nums.filter((_, i) => i % 2 === 1)
      return Math.max(...xs) - Math.min(...xs) >= minSize || Math.max(...ys) - Math.min(...ys) >= minSize
    })
    .map((sub) => `M${sub}`)
    .join('')
}

const [tx, ty] = projection.translate()
const source = `// Generated by scripts/build-route-map.mjs — do not edit by hand.
// Outline: Natural Earth 1:50m (public domain) via world-atlas.

/** Mercator projection parameters (d3-geo, center 0,0, no rotation). */
export const mapProjection = { scale: ${projection.scale().toFixed(4)}, translateX: ${tx.toFixed(4)}, translateY: ${ty.toFixed(4)} }

export const mapSize = { width: ${WIDTH}, height: ${HEIGHT} }

export const landPath = '${dropTinyShapes(path(land))}'

export const argentinaPath = '${dropTinyShapes(path(argentina))}'
`

await writeFile('src/features/home/routeMapGeometry.ts', source)
console.log(`routeMapGeometry.ts: ${(Buffer.byteLength(source) / 1024).toFixed(1)} kB`)
